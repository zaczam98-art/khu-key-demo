// 정확히 같은 이름을 먼저 찾고, 없으면 "마케팅 기획" 처럼 일부만 적힌 이름도 맞춰 봅니다.
export const findJob = (name: string): JobEntry | undefined => {
  const key = name.trim();
  return JOBS.find((j) => j.name === key) ?? JOBS.find((j) => key.length >= 2 && (key.includes(j.name) || j.name.includes(key)));
};
